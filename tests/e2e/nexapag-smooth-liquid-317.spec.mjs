import {test,expect} from '@playwright/test';
test('V3.17 smooth liquid spline has stable card-to-card shape and stage',async({page})=>{
 await page.setViewportSize({width:390,height:844});await page.goto('/v2.html');
 await expect.poll(()=>page.evaluate(()=>window.NexaOrbFlowV35?.renderedFrames)).toBe(49);
 await page.locator('[data-orb-story="income"]').click();
 const first=page.locator('.orb-fluid-ghost[data-kind="income"]');
 await expect(first).toHaveCount(1);
 const frames=await first.evaluate(el=>el.getAnimations()[0].effect.getKeyframes());
 expect(frames).toHaveLength(49);
 expect(frames[0].offset).toBe(0);expect(frames.at(-1).offset).toBe(1);
 expect(frames.every(f=>f.clipPath?.startsWith('polygon('))).toBe(true);
 await expect(first).toHaveCount(0,{timeout:3500});
 const initialHeight=await page.locator('#heroRegion').evaluate(el=>el.getBoundingClientRect().height);
 await page.locator('#orbStoryLayer [data-orb-switch="refund"]').click();
 const morph=page.locator('.orb-fluid-ghost[data-kind="refund"]');
 await expect(morph).toHaveCount(1);
 await expect(morph).toHaveAttribute('data-morph-type','card-to-card');
 const keyframes=await morph.evaluate(el=>el.getAnimations()[0].effect.getKeyframes());
 expect(keyframes).toHaveLength(49);
 const initial=keyframes[0].clipPath,final=keyframes.at(-1).clipPath;
 expect(initial).toContain('polygon(');expect(final).toContain('polygon(');
 await expect(page.locator('.orb-fluid-ghost')).toHaveCount(0,{timeout:3500});
 await expect(page.getByRole('region',{name:'Valor recuperado.'})).toBeVisible();
 const lastHeight=await page.locator('#heroRegion').evaluate(el=>el.getBoundingClientRect().height);
 expect(Math.abs(lastHeight-initialHeight)).toBeLessThanOrEqual(9);
 await page.locator('#orbStoryLayer [data-orb-switch="spending"]').click();
 await expect(page.locator('#homePage')).toHaveClass(/hero-expanded/);
 await expect(page.locator('.orb-fluid-ghost')).toHaveCount(0,{timeout:3500});
 expect(await page.evaluate(()=>document.documentElement.scrollWidth-innerWidth)).toBeLessThanOrEqual(2);
});
test('V3.17 reduced motion skips ghost and respects close on 320px',async({page})=>{
 await page.setViewportSize({width:320,height:744});await page.emulateMedia({reducedMotion:'reduce'});
 await page.goto('/v2.html');await page.locator('[data-orb-story="income"]').click();
 await expect(page.locator('.orb-fluid-ghost')).toHaveCount(0);
 await page.locator('#orbStoryLayer [data-orb-switch="refund"]').click();
 await expect(page.getByRole('region',{name:'Valor recuperado.'})).toBeVisible();
 await expect(page.locator('.orb-fluid-ghost')).toHaveCount(0);
 await page.keyboard.press('Escape');
 await expect(page.locator('#orbStoryLayer')).toHaveCount(0);
});
