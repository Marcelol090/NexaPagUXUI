import {test,expect} from '@playwright/test';
test('V3.15 keeps the old Saídas slide carousel and switches among three orb cards',async({page})=>{
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.setViewportSize({width:390,height:844});await page.goto('/v2.html');
 await expect.poll(()=>page.evaluate(()=>window.NexaOrbFlowV35?.version)).toBe('3.15-shared-carousel');
 await page.locator('[data-orb-story="income"]').click();
 await expect(page.getByRole('region',{name:'Dinheiro que entrou.'})).toBeVisible();
 await expect(page.locator('#orbStoryLayer .orb-flow-switcher button')).toHaveCount(3);
 await page.locator('#orbStoryLayer [data-orb-nav="1"]').click();
 await expect(page.locator('#homePage')).toHaveClass(/hero-expanded/,{timeout:3500});
 await expect(page.locator('.carousel-slide.current')).toHaveAttribute('data-slide','0');
 await expect(page.locator('.orb-fluid-ghost[data-kind="spending"]')).toHaveCount(0,{timeout:3500});
 await page.locator('[data-action="next"]').click();
 await expect(page.locator('.carousel-slide.current')).toHaveAttribute('data-slide','1');
 await page.locator('#expandedHero [data-orb-switch="refund"]').click();
 await expect(page.getByRole('region',{name:'Valor recuperado.'})).toBeVisible({timeout:3500});
 await expect(page.locator('.orb-fluid-ghost[data-kind="refund"]')).toHaveCount(0,{timeout:3500});
 await expect(page.locator('#orbStoryLayer [data-orb-switch="refund"]')).toHaveAttribute('aria-current','true');
 await page.locator('#orbStoryLayer [data-orb-switch="income"]').click();
 await expect(page.getByRole('region',{name:'Dinheiro que entrou.'})).toBeVisible({timeout:3500});
 await expect(page.locator('.orb-fluid-ghost')).toHaveCount(0,{timeout:3500});
 await page.keyboard.press('Escape');
 await expect(page.locator('#orbStoryLayer')).toHaveCount(0,{timeout:3500});
 await expect(page.locator('#compactHero .milestone')).toHaveCount(3);
 expect(errors).toEqual([]);
});
test('V3.15 navigation is inline, readable, dark and reduced-motion resilient',async({page})=>{
 await page.setViewportSize({width:320,height:740});await page.emulateMedia({reducedMotion:'reduce'});
 await page.goto('/v2.html');await page.locator('#themeToggle').click();
 await page.locator('[data-orb-story="refund"]').click();
 await expect(page.locator('#orbStoryLayer')).toHaveAttribute('role','region');
 await expect(page.locator('.orb-story-backdrop')).toHaveCount(0);
 await page.locator('#orbStoryLayer [data-orb-nav="1"]').click();
 await expect(page.getByRole('region',{name:'Dinheiro que entrou.'})).toBeVisible();
 await page.locator('#orbStoryLayer [data-orb-switch="spending"]').click();
 await expect(page.locator('#homePage')).toHaveClass(/hero-expanded/);
 await expect(page.locator('#expandedHero .orb-flow-switcher button')).toHaveCount(3);
 await expect(page.locator('#dock button')).toHaveCount(5);
 expect(await page.evaluate(()=>document.documentElement.scrollWidth-innerWidth)).toBeLessThanOrEqual(2);
});
